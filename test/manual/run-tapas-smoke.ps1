# Assert-Placed checks a tree and its receipt. A tree that ships templates
# (-Rendered) has a placed_hash of its own and rendered records; any other is
# placed as shipped.
function Assert-Placed {
    param([string]$Root, [string]$Placement, [string]$Item, [string]$File = "SKILL.md", [switch]$Rendered)
    $tree = Join-Path $Root $Item
    if (-not (Test-Path (Join-Path $tree $File))) { Fail "$tree\$File is missing" }
    $rcPath = Receipt-Path $Placement $Item
    if (-not (Test-Path $rcPath)) { Fail "receipt $rcPath is missing" }
    $rc = Get-Content -LiteralPath $rcPath -Raw | ConvertFrom-Json
    if ($rc.item -ne $Item -or $rc.placement -ne $Placement -or $rc.version -ne "1.0.0") {
        Fail "receipt $rcPath does not match: $($rc | ConvertTo-Json -Compress)"
    }
    if ($rc.path -ne $tree) { Fail "receipt path '$($rc.path)' is not $tree" }
    if ($rc.tree_hash -notmatch '^sha256:[0-9a-f]{64}$') { Fail "receipt tree_hash '$($rc.tree_hash)'" }
    if ($rc.placed_hash -notmatch '^sha256:[0-9a-f]{64}$') { Fail "receipt placed_hash '$($rc.placed_hash)'" }
    if (-not $rc.PSObject.Properties['rendered']) { Fail "receipt $rcPath has no rendered list" }
    if ($Rendered) {
        if ($rc.placed_hash -eq $rc.tree_hash) { Fail "receipt placed_hash equals tree_hash although $Item renders files" }
        if (@($rc.rendered).Count -eq 0) { Fail "receipt rendered is empty although $Item renders files" }
    } else {
        if ($rc.placed_hash -ne $rc.tree_hash) { Fail "receipt placed_hash '$($rc.placed_hash)' differs from tree_hash '$($rc.tree_hash)'" }
        if (@($rc.rendered).Count -ne 0) { Fail "receipt rendered is not empty: $($rc.rendered | ConvertTo-Json -Compress)" }
    }
    return $rc
}

# Write-DesktopScript writes the Desktop admin fact script: assigned_user,
# which tapas-desktop-managed's .mcp.json.tmpl reads, and
# tapas_desktop_managed, which the manifest's conditional block reads to move
# tapas-desktop-optional into managed_installs.
function Write-DesktopScript {
    param([string]$AssignedUser, [string]$Managed)
    New-Item -ItemType Directory -Path $conditionsDir -Force | Out-Null
    Set-Content -LiteralPath $desktopScript -Encoding ASCII -Value `
        ('@{{ assigned_user = "{0}"; tapas_desktop_managed = "{1}" }} | ConvertTo-Json -Compress' -f $AssignedUser, $Managed)
}

# Get-ReceiptTimes maps every receipt's path to its modification time.
function Get-ReceiptTimes {
    $times = @{}
    foreach ($f in @(Get-ChildItem -LiteralPath $receiptDir -Recurse -File -Filter *.json)) {
        $times[$f.FullName] = $f.LastWriteTimeUtc.Ticks
    }
    return $times
}

function Assert-NotPlaced {
    param([string]$Root, [string]$Placement, [string]$Item)
    $tree = Join-Path $Root $Item
    if (Test-Path $tree) { Fail "$tree exists" }
    $rcPath = Receipt-Path $Placement $Item
    if (Test-Path $rcPath) { Fail "receipt $rcPath exists" }
}

function Wait-Removed {
    param([string]$Root, [string]$Placement, [string]$Item)
    $tree = Join-Path $Root $Item
    $rcPath = Receipt-Path $Placement $Item
    Wait-For { -not (Test-Path $tree) -and -not (Test-Path $rcPath) } "$Item to leave $Placement with its receipt"
}

function Wait-Pruned {
    Wait-For { (Get-YamlList $SelfServe "managed_uninstalls").Count -eq 0 } "managed_uninstalls to be pruned empty"
}

# Assert-LoggedRejection checks that the service log says the zip-only build
# rejected $Item, and returns that line.
function Assert-LoggedRejection {
    param([string]$Item)
    if (-not (Test-Path -LiteralPath $logPath)) { Fail "$logPath is missing" }
    $hits = @(Select-String -LiteralPath $logPath -SimpleMatch "rejected by this zip-only build" |
        Where-Object { $_.Line -match [regex]::Escape($Item) })
    if ($hits.Count -eq 0) { Fail "$logPath does not say $Item was rejected for the zip-only build" }
    return $hits[0].Line
}

# Assert-SkillsIndex checks claude-skills's templated index
# (its files entry in placements.yaml): JSON with the os fact, the
# placement root and exactly the skills placed there.
function Assert-SkillsIndex {
    param([string[]]$Skills)
    if (-not (Test-Path -LiteralPath $skillsIndex)) { Fail "$skillsIndex is missing" }
    $index = Get-Content -LiteralPath $skillsIndex -Raw | ConvertFrom-Json
    if ($index.os -ne "windows") { Fail "skills index os '$($index.os)', want windows" }
    if ($index.root -ne $claudeRoot) { Fail "skills index root '$($index.root)', want $claudeRoot" }
    $names = @(@($index.skills) | ForEach-Object { $_.name } | Sort-Object)
    $want = @($Skills | Sort-Object)
    if (($names -join ",") -ne ($want -join ",")) { Fail "skills index lists '$($names -join ',')', want '$($want -join ',')'" }
}

