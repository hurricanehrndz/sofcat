# Assert-CodexEntry checks one Codex catalog entry: a local source under
# plugins\, the installation policy from the managed flag, and the version
# stamped with the receipt's placed hash.
function Assert-CodexEntry {
    param([string]$Name, [string]$Policy, $Receipt)
    $entry = @(Get-CodexEntry $Name)
    if ($entry.Count -ne 1) { Fail "$Name has $($entry.Count) Codex entries" }
    $e = $entry[0]
    if ($e.source.source -ne "local" -or $e.source.path -ne "./plugins/$Name" -or $e.policy.installation -ne $Policy) {
        Fail "$Name Codex entry: $($e | ConvertTo-Json -Compress -Depth 5), want local ./plugins/$Name, $Policy"
