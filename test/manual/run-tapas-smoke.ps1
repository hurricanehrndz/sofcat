function Read-Json {
    param([string]$Path)
    if (-not (Test-Path -LiteralPath $Path)) { Fail "$Path is missing" }
    return (Get-Content -LiteralPath $Path -Raw | ConvertFrom-Json)
}

# Get-PluginEntry returns the marketplace.json entries named $Name.
function Get-PluginEntry {
    param([string]$Name)
    return @(@((Read-Json $marketplaceJson).plugins) | Where-Object { $_.name -eq $Name })
}

function Get-EnabledPlugins {
    return @((Read-Json $dropIn).enabledPlugins.PSObject.Properties | ForEach-Object { $_.Name })
}

