# Get-Rendered returns the receipt's one rendered record for $File.
function Get-Rendered {
    param($Receipt, [string]$File)
    $recs = @(@($Receipt.rendered) | Where-Object { $_.file -eq $File })
    if ($recs.Count -ne 1) { Fail "receipt for $($Receipt.item) has $($recs.Count) rendered records for ${File}: $($Receipt.rendered | ConvertTo-Json -Compress -Depth 5)" }
    return $recs[0]
}

# Get-FactNames lists, sorted, the facts a rendered record stored as inputs.
function Get-FactNames {
    param($Record)
    return @(@($Record.inputs.facts.PSObject.Properties) | ForEach-Object { $_.Name } | Sort-Object)
}

# Get-FileTimes maps every file under $Root to its modification time.
function Get-FileTimes {
    param([string]$Root)
    $times = @{}
    foreach ($f in @(Get-ChildItem -LiteralPath $Root -Recurse -File -Force)) {
        $times[$f.FullName] = $f.LastWriteTimeUtc.Ticks
    }
    return $times
}

# Assert-OnlyChanged checks that between two Get-FileTimes maps exactly the
# files in $Changed were rewritten.
function Assert-OnlyChanged {
    param($Before, $After, [string[]]$Changed)
    foreach ($path in $Before.Keys) {
        if (-not $After.ContainsKey($path)) { Fail "$path was removed" }
        $expect = $Changed -contains $path
        if ($expect -and $After[$path] -eq $Before[$path]) { Fail "$path was not re-rendered" }
        if (-not $expect -and $After[$path] -ne $Before[$path]) { Fail "$path was rewritten" }
    }
    if ($After.Count -ne $Before.Count) { Fail "files appeared: $($After.Keys -join ', ')" }
}

